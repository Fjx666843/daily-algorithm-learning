#include <bits/stdc++.h>
using namespace std;

const int MAXN = 2e5 + 9;
using ll = long long;
const ll MOD = 998244353;

ll a[MAXN];

// 快速幂：计算 a^b % MOD
ll ksm(ll a, ll b)
{
    ll res = 1;
    while (b > 0)
    {
        if (b & 1)
            res = res * a % MOD;
        a = a * a % MOD;
        b >>= 1;
    }
    return res;
}

// 求逆元：inv(b) = b^(MOD-2) % MOD
ll inv(ll b)
{
    return ksm(b, MOD - 2);
}

void solve()
{
    int n;
    cin >> n;
    for (int i = 1; i <= n; i++)
    {
        cin >> a[i];
    }

    sort(a + 1, a + 1 + n);

    ll ans = 0;
    ll inv2 = inv(2); // 2 的逆元

    for (int i = 1; i <= n; i++)
    {
        ll coef; // 贡献系数

        if (i == 1)
        {
            // 位置 1：只能作为第1小
            // 贡献 = a[1] × 2^(n-1)
            coef = ksm(2, n - 1);
        }
        else if (i == 2)
        {
            // 位置 2：可以作为第1小或第2小
            // 贡献 = a[2] × [2^(n-2) + 1×2^(n-2)] = a[2] × 2^(n-1)
            coef = ksm(2, n - 1);
        }
        else
        {
            // 位置 i >= 3：
            // 贡献系数 = 2^(n-i) × [1 + (i-1) + sum3[i-1]]
            // 其中 sum3[i-1] = (3^(i-1) - 1 - 2(i-1)) / 2

            // 计算 3^(i-1)
            ll pow3 = ksm(3, i - 1);

            // 计算 sum3 = (3^(i-1) - 1 - 2(i-1)) / 2
            ll sum3 = (pow3 - 1 - 2LL * (i - 1)) % MOD;
            if (sum3 < 0)
                sum3 += MOD;
            sum3 = sum3 * inv2 % MOD; // 除以 2

            // 计算 2^(n-i)
            ll pow2 = ksm(2, n - i);

            // 系数 = 2^(n-i) × [1 + (i-1) + sum3]
            ll part = (1 + (i - 1) + sum3) % MOD;
            coef = part * pow2 % MOD;
        }

        ans = (ans + coef * a[i]) % MOD;
    }

    cout << ans << "\n";
}

int main()
{
    ios::sync_with_stdio(0);
    cin.tie(0);
    cout.tie(0);

    int t;
    cin >> t;
    while (t--)
    {
        solve();
    }

    return 0;
}