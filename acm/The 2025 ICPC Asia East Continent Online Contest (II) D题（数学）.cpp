// 对于升序排列的子序列 [a₁, a₂, a₃, ..., aₖ]（a₁ ≤ a₂ ≤ ... ≤ aₖ），其价值为：

// 价值 = a₁ + a₂ + 2×a₃ + 4×a₄ + 8×a₅ + ... + 2^(k-2)×aₖ

// 虽然现在有计算每个子序列价值的公式了，但是枚举每个子序列显然是会超时的，那么我们可以使用贡献法：

